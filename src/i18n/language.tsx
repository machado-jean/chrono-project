export type TranslationKey = keyof (typeof messages)["pt-BR"];

interface LanguageContextValue {
  readonly language: SupportedLanguage;
  readonly setLanguage: (language: SupportedLanguage) => void;
  readonly t: (key: TranslationKey) => string;
  readonly statusLabel: (status: TaskStatus) => string;
  readonly priorityLabel: (priority: TaskPriority) => string;
  readonly projectStatusLabel: (status: ProjectStatus) => string;
  readonly viewLabel: (view: ProjectView) => string;
}

function createLanguageValue(
  language: SupportedLanguage,
  setLanguage: (language: SupportedLanguage) => void,
): LanguageContextValue {
  return {
    language,
    setLanguage,
    t: (key) => messages[language][key],
    statusLabel: (status) => messages[language][`status.${status}`],
    priorityLabel: (priority) => messages[language][`priority.${priority}`],
    projectStatusLabel: (status) => messages[language][`projectStatus.${status}`],
    viewLabel: (view) => messages[language][`view.${view.toLocaleLowerCase()}` as "view.table" | "view.kanban" | "view.gantt"],
  };
}

const LanguageContext = createContext<LanguageContextValue>(
  createLanguageValue("pt-BR", () => undefined),
);

export function detectSystemLanguage(systemLanguages: readonly string[]): SupportedLanguage {
  for (const candidate of systemLanguages) {
    const normalized = candidate.toLocaleLowerCase();
    if (normalized.startsWith("pt")) return "pt-BR";
    if (normalized.startsWith("en")) return "en";
  }
  return "pt-BR";
}

function readInitialLanguage(): SupportedLanguage {
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (saved === "en" || saved === "pt-BR") return saved;
  const systemLanguages = window.navigator.languages.length > 0
    ? window.navigator.languages
    : [window.navigator.language];
  return detectSystemLanguage(systemLanguages);
}

export function LanguageProvider({ children }: { readonly children: ReactNode }) {
  const [language, setLanguage] = useState<SupportedLanguage>(readInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => createLanguageValue(language, setLanguage), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
